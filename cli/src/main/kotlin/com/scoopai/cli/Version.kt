package com.scoopai.cli

import java.util.Properties

/**
 * Version information for scoop-ai.
 *
 * @property version The semantic version string (e.g. "0.1.0").
 * @property commit The git commit hash (short).
 */
data class VersionInfo(
    val version: String,
    val commit: String,
) {
    fun format(): String = "scoop-ai $version (commit $commit)"
}

/**
 * Resolve version information deterministically.
 *
 * @param configuredVersion The version string from build metadata.
 * @param configuredCommit Optional build-time injected commit (from properties file).
 *   Takes priority over [gitRevisionProvider] when non-null and non-blank.
 * @param gitRevisionProvider A function that returns the git revision or null on failure.
 * @return A [VersionInfo] with the resolved commit hash (trimmed, or "unknown").
 */
internal fun resolveVersion(
    configuredVersion: String,
    configuredCommit: String? = null,
    gitRevisionProvider: () -> String? = ::defaultGitRevision,
): VersionInfo {
    val raw = configuredCommit?.takeIf { it.isNotBlank() } ?: gitRevisionProvider()
    val commit = when {
        raw.isNullOrBlank() -> "unknown"
        else -> raw.trim()
    }
    return VersionInfo(configuredVersion, commit)
}

/**
 * Get the short git revision via `git rev-parse --short HEAD`.
 * Returns null if git is unavailable or the command fails.
 */
private fun defaultGitRevision(): String? {
    return try {
        val process = ProcessBuilder("git", "rev-parse", "--short", "HEAD")
            .redirectErrorStream(true)
            .start()
        process.inputStream.bufferedReader().readText().trim().ifBlank { null }
    } catch (_: Exception) {
        null
    }
}

/**
 * Singleton providing version and commit information for the running application.
 *
 * - [VERSION] is read from classpath resource `scoopai-version.properties`
 *   (generated by Gradle `processResources` at build time).
 * - [COMMIT] prefers build-time injected commit from properties file, falling
 *   back to `git rev-parse --short HEAD` at runtime.
 *
 * Both fall back to sensible defaults if unavailable.
 */
object Version {
    val VERSION: String by lazy {
        try {
            val props = Properties()
            val stream = Version::class.java.classLoader.getResourceAsStream("scoopai-version.properties")
            if (stream != null) {
                props.load(stream)
                stream.close()
                props.getProperty("version", "0.0.0-unknown")
            } else {
                "0.0.0-unknown"
            }
        } catch (_: Exception) {
            "0.0.0-unknown"
        }
    }

    private val COMMIT_FROM_BUILD: String? by lazy {
        try {
            val props = Properties()
            val stream = Version::class.java.classLoader.getResourceAsStream("scoopai-version.properties")
            if (stream != null) {
                props.load(stream)
                stream.close()
                props.getProperty("commit")
            } else {
                null
            }
        } catch (_: Exception) {
            null
        }
    }

    val COMMIT: String by lazy {
        COMMIT_FROM_BUILD?.takeIf { it.isNotBlank() }
            ?: defaultGitRevision()
            ?: "unknown"
    }

    /**
     * Full version string like "scoop-ai 0.1.0 (commit xxxxxxx)".
     */
    fun fullVersion(): String = "scoop-ai $VERSION (commit $COMMIT)"
}
